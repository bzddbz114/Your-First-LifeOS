/** Stable pick for a "YYYY-MM-DD": the same day always shows the same line. */
export function quoteOfDay(day: string): Quote {
  let h = 2166136261;
  for (const ch of day) h = Math.imul(h ^ ch.charCodeAt(0), 16777619);
  return QUOTES[(h >>> 0) % QUOTES.length];
}
